import assert from 'node:assert/strict';
import fs from 'node:fs';
import {targets,selectRoles,toTSV} from '../website/dist/entity-core.mjs';
const text='😀 Mira helped Oleg. Later Mira was injured.';
const first=text.indexOf('Mira'),second=text.lastIndexOf('Mira');
const rows=targets(text,[{mention:'Mira',start:first,end:first+4},{mention:'Mira',start:second,end:second+4}]);
assert.equal(rows[0].start,2);assert.ok(rows[1].start>rows[0].start);
assert.throws(()=>targets(text,[{mention:'Mira',start:0,end:4}]));
assert.throws(()=>targets(text,[{mention:'Mira',start:first,end:first+4},{mention:'Mira',start:first,end:first+4}]));
const taxonomy=JSON.parse(fs.readFileSync('website/dist/entity-roles.json','utf8'));
assert.equal(taxonomy.labels.length,22);
const values=taxonomy.labels.map(r=>r.id==='Guardian'?.95:r.id==='Virtuous'?.9:.01);
const result=selectRoles(taxonomy,values);
assert.equal(result.main_role,'Protagonist');assert.deepEqual(new Set(result.labels),new Set(['Guardian','Virtuous']));
const pred={...rows[0],...result};assert.ok(toTSV([pred]).includes('\t2\t6\tProtagonist\t'));
assert.ok(toTSV([pred],'inclusive').includes('\t2\t5\tProtagonist\t'));
assert.throws(()=>toTSV([{...pred,abstained:true}]));
assert.equal(selectRoles(taxonomy,values.map(()=>0)).abstained,true);
console.log('Entity occurrence selection, hierarchy, abstention and TSV offset conventions verified.');
